package main

import (
	"fmt"
	"slices"
	"strings"

	"actionlint.kjanat.dev/v2/internal/checking"
	"actionlint.kjanat.dev/v2/internal/model/rule"
)

func Reference() []byte {
	var b strings.Builder
	b.WriteString("# Rule reference\n\n<!-- Generated by internal/development/generators/rule-docs. DO NOT EDIT. -->\n\nSet each rule's setting to `off`, `on`, `info`, `warn` or `error`.\n\n")
	rules := checking.ListRules()
	slices.SortFunc(rules, func(a, b rule.Descriptor) int { return strings.Compare(a.Name, b.Name) })
	for _, r := range rules {
		fmt.Fprintf(&b, "## %s\n\n%s\n\n%s\n\n", r.Name, r.Explanation, r.Help)
		if r.Provider != "actionlint" {
			fmt.Fprintf(&b, "- Provider: `%s`\n", r.Provider)
		}
		if r.Maturity != rule.StableMaturity {
			fmt.Fprintf(&b, "- Maturity: `%s`\n", r.Maturity)
		}
		fmt.Fprintf(&b, "- Enabled by default: `%t`\n", r.Recommended)
		fmt.Fprintf(&b, "- Setting: `lint.rules.%s.%s`\n\n", checking.RuleCategory(r.Name), r.Name)
		for _, e := range r.Examples {
			if e.Description != "" {
				fmt.Fprintf(&b, "%s\n\n", e.Description)
			}
			fmt.Fprintf(&b, "```yaml\n%s\n```\n\n```yaml\n%s\n```\n\n", e.Before, e.After)
		}
		if e, ok := exampleFollowups[r.Name]; ok {
			fmt.Fprintf(&b, "%s\n\n```yaml\n%s\n```\n\n", e.Description, e.After)
		}
	}
	return []byte(b.String())
}

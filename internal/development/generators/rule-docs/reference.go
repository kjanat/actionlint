package main

import (
	"fmt"
	"slices"
	"strings"

	checking "actionlint.kjanat.dev/v2/internal/checking"
	rule "actionlint.kjanat.dev/v2/internal/checking/rules"
)

// Reference renders documentation from the registered rule declarations.
func Reference() []byte {
	var b strings.Builder
	b.WriteString("# Rule reference\n\n<!-- Generated by internal/development/generators/rule-docs. DO NOT EDIT. -->\n\nCategories describe the subject of a check. Provider and maturity are independent.\n\n")
	rules := checking.ListRules()
	slices.SortFunc(rules, func(a, b rule.Descriptor) int { return strings.Compare(a.Name, b.Name) })
	for _, r := range rules {
		fmt.Fprintf(&b, "## %s\n\n%s\n\n%s\n\n- Category: `%s/%s`\n- Provider: `%s`\n- Maturity: `%s`\n- Enabled by default: `%t`\n\n", r.Name, r.Explanation, r.Help, r.Category, r.Subcategory, r.Provider, r.Maturity, r.Recommended)
		fmt.Fprintf(&b, "Configure this rule with `lint.rules.%s.%s`. Use `off`, `on`, `info`, `warn` or `error`; findings at every enabled level affect the CLI exit status.\n\n", checking.RuleCategory(r.Name), r.Name)
		for _, e := range r.Examples {
			fmt.Fprintf(&b, "%s\n\n```yaml\n%s\n```\n\n```yaml\n%s\n```\n\n", e.Description, e.Before, e.After)
		}
		if e, ok := exampleFollowups[r.Name]; ok {
			fmt.Fprintf(&b, "%s\n\n```yaml\n%s\n```\n\n", e.Description, e.After)
		}
	}
	return []byte(b.String())
}

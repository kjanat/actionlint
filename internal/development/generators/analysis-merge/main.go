// Command analysis-merge generates the field-wise analysis aggregation.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"go/types"
	"os"
	"path/filepath"
	"reflect"

	"golang.org/x/tools/go/packages"
)

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if err := run(*root); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string) error {
	pkgs, err := packages.Load(&packages.Config{Dir: root, Mode: packages.NeedName | packages.NeedTypes | packages.NeedImports | packages.NeedDeps}, "./internal/results/report")
	if err != nil {
		return err
	}
	if len(pkgs) != 1 || len(pkgs[0].Errors) != 0 {
		return fmt.Errorf("load report types: %v", pkgs)
	}
	obj := pkgs[0].Types.Scope().Lookup("Analysis")
	if obj == nil {
		return errors.New("report.Analysis is missing")
	}
	fields, ok := obj.Type().Underlying().(*types.Struct)
	if !ok {
		return errors.New("report.Analysis is not a struct")
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by internal/development/generators/analysis-merge; DO NOT EDIT.\n\npackage report\n\nfunc appendAnalysis(dst *Analysis, part Analysis) {")
	custom := map[string]bool{}
	for i := range fields.NumFields() {
		field := fields.Field(i)
		mode := reflect.StructTag(fields.Tag(i)).Get("merge")
		switch mode {
		case "append":
			if _, ok := field.Type().Underlying().(*types.Slice); !ok {
				return fmt.Errorf("analysis field %s: append requires a slice", field.Name())
			}
			fmt.Fprintf(&out, "dst.%s = append(dst.%s, part.%s...)\n", field.Name(), field.Name(), field.Name())
		case "sum":
			if !types.Identical(field.Type(), types.Typ[types.Int]) {
				return fmt.Errorf("analysis field %s: sum requires int", field.Name())
			}
			fmt.Fprintf(&out, "dst.%s += part.%s\n", field.Name(), field.Name())
		case "captured", "rules":
			if mode == "captured" && field.Name() != "CapturedSources" || mode == "rules" && field.Name() != "Rules" || custom[mode] {
				return fmt.Errorf("analysis field %s: invalid custom merge %q", field.Name(), mode)
			}
			custom[mode] = true
		default:
			return fmt.Errorf("analysis field %s requires a supported merge contract", field.Name())
		}
	}
	if !custom["captured"] || !custom["rules"] {
		return errors.New("analysis must declare captured and rules merge contracts")
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	path := filepath.Join(root, "internal/results/report/analysis_merge.gen.go")
	if os.Getenv("ANALYSIS_MERGE_CHECK") == "1" {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, formatted) {
			return fmt.Errorf("%s is stale; run go generate ./internal/results/report", path)
		}
		return nil
	}
	return os.WriteFile(path, formatted, 0o644)
}

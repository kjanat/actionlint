// Command owned-copies generates type-checked ownership copies.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

type generator struct {
	pkg       *types.Package
	rootKeys  map[string]bool
	intern    bool
	imports   map[string]string
	aliases   map[string]string
	helpers   map[string]string
	names     map[string]string
	pending   []types.Type
	functions bytes.Buffer
}

func main() {
	check := flag.Bool("check", os.Getenv("OWNED_COPIES_CHECK") == "1", "check that generated output is current")
	root := flag.String("root", ".", "repository root")
	packagePath := flag.String("package", "./internal/results/finding", "package containing the root type")
	typeName := flag.String("type", "Finding", "comma-separated root types to copy")
	output := flag.String("output", "internal/results/finding/owned_copy.gen.go", "output path relative to the repository root")
	flag.Parse()
	if err := run(*root, *packagePath, *typeName, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root, packagePath, typeName, outputPath string, check bool) error {
	pkgs, err := packages.Load(&packages.Config{Dir: root, Mode: packages.NeedName | packages.NeedTypes | packages.NeedImports | packages.NeedDeps}, packagePath)
	if err != nil {
		return err
	}
	if len(pkgs) != 1 {
		return fmt.Errorf("load %s: got %d packages", packagePath, len(pkgs))
	}
	if len(pkgs[0].Errors) != 0 {
		return fmt.Errorf("load %s: %v", packagePath, pkgs[0].Errors)
	}
	g := &generator{pkg: pkgs[0].Types, rootKeys: map[string]bool{}, imports: map[string]string{}, aliases: map[string]string{}, helpers: map[string]string{}, names: map[string]string{}}
	var roots []types.Type
	for name := range strings.SplitSeq(typeName, ",") {
		name = strings.TrimSpace(name)
		rootType := g.pkg.Scope().Lookup(name)
		if rootType == nil {
			return fmt.Errorf("type %s is missing from %s", name, packagePath)
		}
		t := types.Unalias(rootType.Type())
		if _, ok := t.(*types.Named); !ok {
			return fmt.Errorf("root %s must be a named type", name)
		}
		key := typeKey(t)
		if g.rootKeys[key] {
			return fmt.Errorf("duplicate root %s", name)
		}
		g.rootKeys[key] = true
		roots = append(roots, t)
		intern, err := hasIntern(t, map[types.Type]bool{})
		if err != nil {
			return fmt.Errorf("root %s: %w", name, err)
		}
		g.intern = g.intern || intern
	}
	for _, t := range roots {
		if _, err := g.helper(t); err != nil {
			return err
		}
	}
	for len(g.pending) != 0 {
		t := g.pending[0]
		g.pending = g.pending[1:]
		if err := g.emit(t); err != nil {
			return err
		}
	}
	var output bytes.Buffer
	fmt.Fprintf(&output, "// Code generated by internal/development/generators/owned-copies; DO NOT EDIT.\n\npackage %s\n", g.pkg.Name())
	if len(g.imports) != 0 {
		fmt.Fprintln(&output, "\nimport (")
		paths := make([]string, 0, len(g.imports))
		for path := range g.imports {
			paths = append(paths, path)
		}
		sort.Slice(paths, func(i, j int) bool {
			left, right := externalImport(paths[i]), externalImport(paths[j])
			if left != right {
				return !left
			}
			return paths[i] < paths[j]
		})
		for i, path := range paths {
			if i > 0 && externalImport(path) != externalImport(paths[i-1]) {
				fmt.Fprintln(&output)
			}
			fmt.Fprintf(&output, "\t%s %q\n", g.imports[path], path)
		}
		fmt.Fprintln(&output, ")")
	}
	if g.intern {
		fmt.Fprint(&output, `
type ownedCopyBytesKey struct { first *byte; length int }
type ownedCopyContext struct { buffers map[ownedCopyBytesKey][]byte }
func (ctx *ownedCopyContext) copyOwnedInternedBytes(in []byte) []byte {
 if in == nil { return nil }
 if len(in) == 0 { return make([]byte, 0) }
 key := ownedCopyBytesKey{first: &in[0], length: len(in)}
 if prior, ok := ctx.buffers[key]; ok { return prior }
 if ctx.buffers == nil { ctx.buffers = make(map[ownedCopyBytesKey][]byte) }
 out := make([]byte, len(in)); copy(out, in); ctx.buffers[key] = out; return out
}
`)
		for _, t := range roots {
			rootName := g.helpers[typeKey(t)]
			rootTypeName := types.TypeString(t, g.qualifier)
			fmt.Fprintf(&output, "func %s(in %s) %s { return new(ownedCopyContext).%s(in) }\n", rootName, rootTypeName, rootTypeName, rootName)
		}
	}
	output.Write(g.functions.Bytes())
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return fmt.Errorf("format generated copies: %w\n%s", err, output.String())
	}
	path := filepath.Join(root, filepath.FromSlash(outputPath))
	if check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, formatted) {
			return fmt.Errorf("%s is stale; rerun go generate for %s", path, packagePath)
		}
		return nil
	}
	return os.WriteFile(path, formatted, 0o644)
}

func externalImport(path string) bool {
	first, _, _ := strings.Cut(path, "/")
	return strings.Contains(first, ".")
}

func (g *generator) qualifier(pkg *types.Package) string {
	if pkg.Path() == g.pkg.Path() {
		return ""
	}
	if alias, ok := g.imports[pkg.Path()]; ok {
		return alias
	}
	alias := pkg.Name()
	for i := 2; g.aliases[alias] != "" && g.aliases[alias] != pkg.Path(); i++ {
		alias = fmt.Sprintf("%s%d", pkg.Name(), i)
	}
	g.imports[pkg.Path()], g.aliases[alias] = alias, pkg.Path()
	return alias
}

func typeKey(t types.Type) string {
	return types.TypeString(t, func(p *types.Package) string { return p.Path() })
}

// hasIntern discovers explicit immutable byte-sharing contracts recursively.
func hasIntern(t types.Type, seen map[types.Type]bool) (bool, error) {
	t = types.Unalias(t)
	if seen[t] {
		return false, nil
	}
	seen[t] = true
	switch typ := t.(type) {
	case *types.Named:
		return hasIntern(typ.Underlying(), seen)
	case *types.Pointer:
		return hasIntern(typ.Elem(), seen)
	case *types.Slice:
		return hasIntern(typ.Elem(), seen)
	case *types.Array:
		return hasIntern(typ.Elem(), seen)
	case *types.Map:
		return hasIntern(typ.Elem(), seen)
	case *types.Struct:
		found := false
		for i := range typ.NumFields() {
			field := typ.Field(i)
			contract := reflect.StructTag(typ.Tag(i)).Get("clone")
			if contract == "shared" {
				continue
			}
			if contract == "intern" {
				if !types.Identical(field.Type(), types.NewSlice(types.Typ[types.Byte])) {
					return false, fmt.Errorf("field %s: clone intern requires []byte", field.Name())
				}
				found = true
				continue
			}
			nested, err := hasIntern(field.Type(), seen)
			if err != nil {
				return false, fmt.Errorf("field %s: %w", field.Name(), err)
			}
			found = found || nested
		}
		return found, nil
	}
	return false, nil
}

func (g *generator) helper(t types.Type) (string, error) {
	t = types.Unalias(t)
	if err := g.accessible(t); err != nil {
		return "", err
	}
	key := typeKey(t)
	if name, ok := g.helpers[key]; ok {
		return name, nil
	}
	name := "Value"
	if named, ok := t.(*types.Named); ok {
		name = named.Obj().Name()
	}
	if g.rootKeys[key] {
		name = "copyOwned" + name
	} else {
		sum := sha256.Sum256([]byte(key))
		name = fmt.Sprintf("copyOwned%s_%x", name, sum[:16])
	}
	if existing := g.names[name]; existing != "" && existing != key {
		return "", fmt.Errorf("copy helper %s conflicts for %s and %s", name, existing, key)
	}
	g.names[name] = key
	g.helpers[key] = name
	g.pending = append(g.pending, t)
	return name, nil
}

// A helper signature cannot name private types from another package.
func (g *generator) accessible(t types.Type) error {
	t = types.Unalias(t)
	switch typ := t.(type) {
	case *types.Named:
		if pkg := typ.Obj().Pkg(); pkg != nil && pkg.Path() != g.pkg.Path() && !typ.Obj().Exported() {
			return fmt.Errorf("cannot copy inaccessible type %s", typeKey(t))
		}
		for t := range typ.TypeArgs().Types() {
			if err := g.accessible(t); err != nil {
				return err
			}
		}
	case *types.Pointer:
		return g.accessible(typ.Elem())
	case *types.Slice:
		return g.accessible(typ.Elem())
	case *types.Array:
		return g.accessible(typ.Elem())
	case *types.Map:
		if err := g.accessible(typ.Key()); err != nil {
			return err
		}
		return g.accessible(typ.Elem())
	}
	return nil
}

// mutable checks the whole type, including private fields. Foreign private
// references require a shared contract, since generated code cannot access them.
func (g *generator) mutable(t types.Type, active map[types.Type]bool) (bool, error) {
	t = types.Unalias(t)
	if active[t] {
		return false, nil
	}
	active[t] = true
	defer delete(active, t)
	switch typ := t.(type) {
	case *types.Named:
		return g.mutable(typ.Underlying(), active)
	case *types.Basic:
		if typ.Kind() == types.UnsafePointer {
			return false, fmt.Errorf("unsafe pointer in %s", typeKey(t))
		}
		return false, nil
	case *types.Pointer, *types.Slice, *types.Map:
		return true, nil
	case *types.Array:
		return g.mutable(typ.Elem(), active)
	case *types.Struct:
		found := false
		for i := range typ.NumFields() {
			field := typ.Field(i)
			contract := reflect.StructTag(typ.Tag(i)).Get("clone")
			if contract == "shared" {
				continue
			}
			if contract != "" && contract != "intern" {
				return false, fmt.Errorf("unsupported clone contract %q on %s", contract, field.Name())
			}
			changed, err := g.mutable(field.Type(), active)
			if err != nil {
				return false, fmt.Errorf("field %s: %w", field.Name(), err)
			}
			if changed && !field.Exported() && field.Pkg() != g.pkg {
				return false, fmt.Errorf("mutable unexported field %s requires an explicit ownership contract", field.Name())
			}
			found = found || changed
		}
		return found, nil
	default:
		return false, fmt.Errorf("unsupported ownership type %s", typeKey(t))
	}
}

func (g *generator) expression(t types.Type, value string) (string, error) {
	needsCopy, err := g.mutable(t, map[types.Type]bool{})
	if err != nil {
		return "", err
	}
	if !needsCopy {
		return value, nil
	}
	var element types.Type
	var library string
	switch container := t.Underlying().(type) {
	case *types.Slice:
		element, library = container.Elem(), "slices"
	case *types.Map:
		mutableKey, err := g.mutable(container.Key(), map[types.Type]bool{})
		if err != nil {
			return "", err
		}
		if mutableKey {
			return "", fmt.Errorf("map %s has mutable keys", typeKey(t))
		}
		element, library = container.Elem(), "maps"
	}
	if element != nil {
		mutableElement, err := g.mutable(element, map[types.Type]bool{})
		if err != nil {
			return "", err
		}
		if !mutableElement {
			return g.qualifier(types.NewPackage(library, library)) + ".Clone(" + value + ")", nil
		}
	}
	name, err := g.helper(t)
	if err != nil {
		return "", err
	}
	if g.intern {
		name = "ctx." + name
	}
	return name + "(" + value + ")", nil
}

func (g *generator) emit(t types.Type) error {
	name := g.helpers[typeKey(t)]
	typeName := types.TypeString(t, g.qualifier)
	receiver := ""
	if g.intern {
		receiver = "(ctx *ownedCopyContext) "
	}
	fmt.Fprintf(&g.functions, "\nfunc %s%s(in %s) %s {\n", receiver, name, typeName, typeName)
	underlying := t.Underlying()
	switch typ := underlying.(type) {
	case *types.Struct:
		fmt.Fprintln(&g.functions, "out := in")
		for i := range typ.NumFields() {
			field := typ.Field(i)
			contract := reflect.StructTag(typ.Tag(i)).Get("clone")
			if contract == "shared" {
				continue
			}
			if contract == "intern" {
				fmt.Fprintf(&g.functions, "out.%s = ctx.copyOwnedInternedBytes(in.%s)\n", field.Name(), field.Name())
				continue
			}
			expr, err := g.expression(field.Type(), "in."+field.Name())
			if err != nil {
				return fmt.Errorf("%s.%s: %w", typeKey(t), field.Name(), err)
			}
			if expr != "in."+field.Name() {
				fmt.Fprintf(&g.functions, "out.%s = %s\n", field.Name(), expr)
			}
		}
		fmt.Fprintln(&g.functions, "return out")
	case *types.Pointer:
		value, err := g.expression(typ.Elem(), "*in")
		if err != nil {
			return err
		}
		fmt.Fprintf(&g.functions, "if in == nil { return nil }; out := %s; return (%s)(&out)\n", value, typeName)
	case *types.Slice:
		value, err := g.expression(typ.Elem(), "in[i]")
		if err != nil {
			return err
		}
		fmt.Fprintf(&g.functions, "if in == nil { return nil }; out := make(%s, len(in)); for i := range in { out[i] = %s }; return out\n", typeName, value)
	case *types.Map:
		keyMutable, err := g.mutable(typ.Key(), map[types.Type]bool{})
		if err != nil {
			return err
		}
		if keyMutable {
			return fmt.Errorf("map %s has mutable keys", typeKey(t))
		}
		value, err := g.expression(typ.Elem(), "value")
		if err != nil {
			return err
		}
		fmt.Fprintf(&g.functions, "if in == nil { return nil }; out := make(%s, len(in)); for key, value := range in { out[key] = %s }; return out\n", typeName, value)
	case *types.Array:
		value, err := g.expression(typ.Elem(), "in[i]")
		if err != nil {
			return err
		}
		fmt.Fprintf(&g.functions, "out := in; for i := range in { out[i] = %s }; return out\n", value)
	default:
		return fmt.Errorf("cannot generate copy for %s", typeKey(t))
	}
	fmt.Fprintln(&g.functions, "}")
	return nil
}

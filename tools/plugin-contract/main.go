// Command plugin-contract generates the host's expected analyzer type graph.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"go.bytecodealliance.org/wit"
)

const (
	contractPath = "../../plugins/wit/analyzer.wit"
	outputPath   = "../../internal/plugins/component/contract_generated.go"
)

func main() {
	fixtures := flag.Bool("fixtures", false, "also regenerate structural compatibility fixtures using wasm-tools")
	flag.Parse()
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := generateRunner(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if *fixtures {
		if err := generateFixtures(); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

func generate() error {
	data, err := os.ReadFile(contractPath)
	if err != nil {
		return err
	}
	resolved, err := wit.DecodeWIT(bytes.NewReader(data))
	if err != nil {
		return err
	}
	var analyzer *wit.Interface
	for _, iface := range resolved.Interfaces {
		if iface.Match("kjanat:actionlint/analyzer") {
			analyzer = iface
			break
		}
	}
	if analyzer == nil {
		return fmt.Errorf("canonical analyzer interface missing")
	}
	g := generator{types: make(map[*wit.TypeDef]string)}
	fmt.Fprintln(&g.output, "// Code generated by tools/plugin-contract from plugins/wit/analyzer.wit. DO NOT EDIT.")
	fmt.Fprintln(&g.output, "package component")
	fmt.Fprintln(&g.output, `import wp "github.com/partite-ai/wacogo/wasmparser"`)
	identity := analyzer.Package.Name
	identity.Extension = *analyzer.Name
	fmt.Fprintln(&g.output, "const (")
	fmt.Fprintf(&g.output, "canonicalAnalyzerInterface = %q\n", identity.String())
	fmt.Fprintf(&g.output, "canonicalContractDigest = %q\n", fmt.Sprintf("%x", sha256.Sum256(bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n")))))
	fmt.Fprintln(&g.output, ")")
	fmt.Fprintln(&g.output, "func expectedAnalyzerContract() *wp.ComponentType {")
	fmt.Fprintln(&g.output, "b := wp.NewArena(wp.DefaultFeatures()).HostTypeBuilder()")
	var exports []string
	for name, td := range analyzer.TypeDefs.All() {
		expr, err := g.value(td)
		if err != nil {
			return err
		}
		exports = append(exports, fmt.Sprintf("%q: {Kind: wp.EntityType, TypeRef: wp.ComponentAnyTypeID{Kind: wp.AnyTypeDefined, Index: uint32(%s.TypeID)}},", name, expr))
	}
	for name, fn := range analyzer.Functions.All() {
		params, err := g.params(fn.Params)
		if err != nil {
			return err
		}
		results, err := g.params(fn.Results)
		if err != nil {
			return err
		}
		exports = append(exports, fmt.Sprintf("%q: {Kind: wp.EntityFunc, FuncID: b.PushFuncType(wp.FuncTypeDesc{Params: %s, Results: %s})},", name, params, results))
	}
	fmt.Fprintf(&g.output, "analyzer := b.PushInstanceType(wp.InstanceTypeDesc{Exports: map[string]wp.ComponentEntityType{\n%s\n}})\n", strings.Join(exports, "\n"))
	fmt.Fprintln(&g.output, "plugin := b.PushInstanceType(wp.InstanceTypeDesc{Exports: map[string]wp.ComponentEntityType{AnalyzerInterface: {Kind: wp.EntityInstance, InstID: analyzer}}})")
	fmt.Fprintln(&g.output, `return b.NewComponentTypeHandle(b.PushComponentType(wp.ComponentTypeDesc{Imports: map[string]wp.ComponentEntityType{"plugin": {Kind: wp.EntityInstance, InstID: plugin}}, ImportOrder: []string{"plugin"}}))`)
	fmt.Fprintln(&g.output, "}")
	fmt.Fprintln(&g.output, "var (")
	for name, td := range analyzer.TypeDefs.All() {
		enum, ok := td.Kind.(*wit.Enum)
		if !ok {
			continue
		}
		var names []string
		for _, item := range enum.Cases {
			names = append(names, strconv.Quote(item.Name))
		}
		identifier := strings.ReplaceAll(name, "-", "_")
		fmt.Fprintf(&g.output, "canonical_%s = []string{%s}\n", identifier, strings.Join(names, ","))
	}
	fmt.Fprintln(&g.output, ")")
	formatted, err := format.Source(g.output.Bytes())
	if err != nil {
		return fmt.Errorf("format generated contract: %w", err)
	}
	return os.WriteFile(outputPath, formatted, 0o644)
}

type generator struct {
	output bytes.Buffer
	types  map[*wit.TypeDef]string
}

func (g *generator) params(params []wit.Param) (string, error) {
	var fields []string
	for _, param := range params {
		value, err := g.value(param.Type)
		if err != nil {
			return "", err
		}
		fields = append(fields, fmt.Sprintf("{Name:%q, Type:%s}", param.Name, value))
	}
	return "[]wp.FuncParamDesc{" + strings.Join(fields, ",") + "}", nil
}

func (g *generator) value(value wit.Type) (string, error) {
	switch value := value.(type) {
	case wit.Bool:
		return "wp.ValTypeDesc{IsPrimitive:true, Primitive:wp.PrimBool}", nil
	case wit.U32:
		return "wp.ValTypeDesc{IsPrimitive:true, Primitive:wp.PrimU32}", nil
	case wit.String:
		return "wp.ValTypeDesc{IsPrimitive:true, Primitive:wp.PrimString}", nil
	case *wit.TypeDef:
		if name, ok := g.types[value]; ok {
			return name, nil
		}
		desc, err := g.defined(value.Kind)
		if err != nil {
			return "", err
		}
		name := fmt.Sprintf("t%d", len(g.types))
		g.types[value] = name
		fmt.Fprintf(&g.output, "%s := wp.ValTypeDesc{TypeID:b.PushDefinedType(%s)}\n", name, desc)
		return name, nil
	default:
		return "", fmt.Errorf("unsupported canonical type %T", value)
	}
}

func (g *generator) defined(kind wit.TypeDefKind) (string, error) {
	switch kind := kind.(type) {
	case *wit.Record:
		var fields []string
		for _, field := range kind.Fields {
			value, err := g.value(field.Type)
			if err != nil {
				return "", err
			}
			fields = append(fields, fmt.Sprintf("{Name:%q, Type:%s}", field.Name, value))
		}
		return "wp.DefinedTypeDesc{Kind:wp.DefinedKindRecord, Record:&wp.RecordTypeDesc{Fields:[]wp.FieldDesc{" + strings.Join(fields, ",") + "}}}", nil
	case *wit.Enum:
		var names []string
		for _, item := range kind.Cases {
			names = append(names, strconv.Quote(item.Name))
		}
		return "wp.DefinedTypeDesc{Kind:wp.DefinedKindEnum, Enum:[]string{" + strings.Join(names, ",") + "}}", nil
	case *wit.List:
		value, err := g.value(kind.Type)
		return "wp.DefinedTypeDesc{Kind:wp.DefinedKindList, List:" + value + "}", err
	case *wit.Option:
		value, err := g.value(kind.Type)
		return "wp.DefinedTypeDesc{Kind:wp.DefinedKindOption, Option:" + value + "}", err
	case *wit.Variant:
		var cases []string
		for _, item := range kind.Cases {
			payload := "wp.None[wp.ValTypeDesc]()"
			if item.Type != nil {
				value, err := g.value(item.Type)
				if err != nil {
					return "", err
				}
				payload = "wp.Some(" + value + ")"
			}
			cases = append(cases, fmt.Sprintf("{Name:%q, Type:%s}", item.Name, payload))
		}
		return "wp.DefinedTypeDesc{Kind:wp.DefinedKindVariant, Variant:&wp.VariantTypeDesc{Cases:[]wp.VariantCaseDesc{" + strings.Join(cases, ",") + "}}}", nil
	default:
		return "", fmt.Errorf("unsupported canonical definition %T", kind)
	}
}

package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"

	"go-modules.kjanat.dev/wit"
)

func generateRunner() error {
	return generateRoleContract("runner", "runner-provider", "RunnerInterface", "runnerContractDigest", "expectedRunnerContract")
}

// generateScriptEngine generates every script-engine version the host accepts.
func generateScriptEngine() error {
	if err := generateRoleContract("script-engine", "script-engine", "ScriptEngineInterface", "scriptEngineContractDigest", "expectedScriptEngineContract"); err != nil {
		return err
	}
	return generateContract(roleContract{
		source: "0.3.0/script-engine.wit", role: "script-engine", interfaceName: "ScriptEngine03Interface",
		digestName: "scriptEngine03ContractDigest", functionName: "expectedScriptEngine03Contract",
		prefix: "script_engine_03", output: "script_engine_03.gen.go",
	})
}

// roleContract names one generated role contract. Source is relative to the
// WIT directory; prefix starts the generated enum variable names and output
// is the generated file in internal/plugins/component.
type roleContract struct {
	source, role, interfaceName, digestName, functionName, prefix, output string
}

// generateRoleContract generates the contract of a role defined in the
// current package's file.wit.
func generateRoleContract(file, role, interfaceName, digestName, functionName string) error {
	identifier := strings.ReplaceAll(file, "-", "_")
	return generateContract(roleContract{
		source: file + ".wit", role: role, interfaceName: interfaceName, digestName: digestName,
		functionName: functionName, prefix: identifier, output: identifier + ".gen.go",
	})
}

func generateContract(spec roleContract) error {
	data, err := os.ReadFile("../../crates/actionlint-extension-api/wit/" + spec.source)
	if err != nil {
		return err
	}
	role, interfaceName, digestName, functionName := spec.role, spec.interfaceName, spec.digestName, spec.functionName
	contractData := data
	if spec.source == "template-effects.wit" {
		dependency, err := os.ReadFile("../../crates/actionlint-extension-api/wit/script-engine.wit")
		if err != nil {
			return err
		}
		contractData = append(append([]byte{}, dependency...), []byte(strings.TrimPrefix(string(data), "package kjanat:actionlint@0.2.0;"))...)
	}
	resolved, err := wit.DecodeWIT(bytes.NewReader(contractData))
	if err != nil {
		return err
	}
	for _, iface := range resolved.Interfaces {
		if !iface.Match("kjanat:actionlint/" + role) {
			continue
		}
		g := generator{types: make(map[*wit.TypeDef]string)}
		fmt.Fprintf(&g.output, "// Code generated by tools/plugin-contract from crates/actionlint-extension-api/wit/%s. DO NOT EDIT.\n", spec.source)
		fmt.Fprintln(&g.output, "package component")
		fmt.Fprintln(&g.output, `import wp "github.com/kjanat/wacogo/wasmparser"`)
		identity := iface.Package.Name
		identity.Extension = *iface.Name
		fmt.Fprintf(&g.output, "const (\n%s = %q\n", interfaceName, identity.String())
		fmt.Fprintf(&g.output, "%s = %q\n)\n", digestName, fmt.Sprintf("%x", sha256.Sum256(bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n")))))
		fmt.Fprintf(&g.output, "func %s() *wp.ComponentType {\n", functionName)
		fmt.Fprintln(&g.output, "b := wp.NewArena(wp.DefaultFeatures()).HostTypeBuilder()")
		var exports []string
		for name, td := range iface.TypeDefs.All() {
			expr, err := g.value(td)
			if err != nil {
				return err
			}
			exports = append(exports, fmt.Sprintf("%q: {Kind: wp.EntityType, TypeRef: wp.ComponentAnyTypeID{Kind: wp.AnyTypeDefined, Index: uint32(%s.TypeID)}},", name, expr))
		}
		for name, fn := range iface.Functions.All() {
			params, err := g.params(fn.Params)
			if err != nil {
				return err
			}
			results, err := g.params(fn.Results)
			if err != nil {
				return err
			}
			exports = append(exports, fmt.Sprintf("%q: {Kind: wp.EntityFunc, FuncID: b.PushFuncType(wp.FuncTypeDesc{Params: %s, Results: %s})},", name, params, results))
		}
		fmt.Fprintf(&g.output, "provider := b.PushInstanceType(wp.InstanceTypeDesc{Exports: map[string]wp.ComponentEntityType{\n%s\n}})\n", strings.Join(exports, "\n"))
		fmt.Fprintf(&g.output, "plugin := b.PushInstanceType(wp.InstanceTypeDesc{Exports: map[string]wp.ComponentEntityType{%s: {Kind: wp.EntityInstance, InstID: provider}}})\n", interfaceName)
		fmt.Fprintln(&g.output, `return b.NewComponentTypeHandle(b.PushComponentType(wp.ComponentTypeDesc{Imports: map[string]wp.ComponentEntityType{"plugin": {Kind: wp.EntityInstance, InstID: plugin}}, ImportOrder: []string{"plugin"}}))`)
		fmt.Fprintln(&g.output, "}")
		var enums []string
		for name, td := range iface.TypeDefs.All() {
			var names []string
			switch kind := td.Kind.(type) {
			case *wit.Enum:
				for _, item := range kind.Cases {
					names = append(names, strconv.Quote(item.Name))
				}
			case *wit.Variant:
				for _, item := range kind.Cases {
					names = append(names, strconv.Quote(item.Name))
				}
			default:
				continue
			}
			enums = append(enums, fmt.Sprintf("%s_%s = []string{%s}", spec.prefix, strings.ReplaceAll(name, "-", "_"), strings.Join(names, ",")))
		}
		if len(enums) == 1 {
			fmt.Fprintf(&g.output, "var %s\n", enums[0])
		} else if len(enums) > 1 {
			fmt.Fprintf(&g.output, "var (\n%s\n)\n", strings.Join(enums, "\n"))
		}
		formatted, err := format.Source(g.output.Bytes())
		if err != nil {
			return err
		}
		return os.WriteFile("../../internal/plugins/component/"+spec.output, formatted, 0o644)
	}
	return fmt.Errorf("canonical %s interface missing", role)
}
